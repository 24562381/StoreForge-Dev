export function generateCode128SVG(text: string, height: number = 38) {
  const clean = (text || 'WWM000101').replace(BARCODE_CHAR_REGEX, '').toUpperCase() || 'WWM000101';
  const codes: number[] = [104];
  let checkSum = 104;

  for (let i = 0; i < clean.length; i++) {
    const code = clean.charCodeAt(i) - 32;
    if (code >= 0 && code <= 95) {
      codes.push(code);
      checkSum += code * (i + 1);
    }
  }

  const checkDigit = checkSum % 103;
  codes.push(checkDigit);
  codes.push(106);

  const barElements: { x: number; w: number }[] = [];
  let currentX = 2;

  codes.forEach((c) => {
    const pattern = CODE128_PATTERNS[c] || CODE128_PATTERNS[0];
    pattern.forEach((width, pIdx) => {
      const isBar = pIdx % 2 === 0;
      if (isBar) {
        barElements.push({ x: currentX, w: width });
      }
      currentX += width;
    });
  });

  const totalWidth = currentX + 2;

  return (
    <svg 
      className="barcode-svg" 
      role="img" 
      aria-label={`Barcode for ${clean}`} 
      viewBox={`0 0 ${totalWidth} ${height}`} 
      preserveAspectRatio="xMinYMin meet" 
      xmlns="http://www.w3.org/2000/svg"
    >
      {barElements.map((bar, idx) => (
        <rect key={idx} x={bar.x} y="0" width={bar.w} height={height} fill="#000000" />
      ))}
    </svg>
  );
}
